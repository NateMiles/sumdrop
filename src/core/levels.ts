export const levelById = (id: string): LevelDef | undefined => LEVELS.find((l) => l.id === id);

export function nextLevel(id: string): LevelDef | undefined {
  const i = LEVELS.findIndex((l) => l.id === id);
  return i >= 0 ? LEVELS[i + 1] : undefined;
}
